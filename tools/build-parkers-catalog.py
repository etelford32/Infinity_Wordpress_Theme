#!/usr/bin/env python3
"""Build inc/parkers-catalog.php from Parker's Physics' simulations.html.

The hub page (page-parkers-physics.php) lists every Parker's Physics
simulation. The list lives in that site's own catalog page, so this
script reads it and writes a plain PHP array the theme can render with
no network call. Re-run it whenever Parker's Physics adds simulations:

  git clone --depth 1 https://github.com/etelford32/parkersphysics /tmp/pp
  tools/build-parkers-catalog.py /tmp/pp/simulations.html

Card icons are copied as SVG markup; anything other than basic shape
elements is rejected, so the generated file only ever holds static
drawing markup.
"""
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'inc', 'parkers-catalog.php')

ALLOWED_SVG = {'path', 'circle', 'ellipse', 'rect', 'g', 'line', 'polyline', 'polygon'}


def text(fragment):
    return html.unescape(re.sub(r'<[^>]+>', '', fragment)).strip()


def php_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main(src):
    page = open(src, encoding='utf-8').read()

    sections = []
    for m in re.finditer(r'<section class="sim-section" data-section="([^"]+)".*?</section>', page, re.S):
        key, body = m.group(1), m.group(0)
        title = text(re.search(r'class="sim-section-title"[^>]*>(.*?)</h2>', body, re.S).group(1))
        note_m = re.search(r'class="sim-section-note">(.*?)</p>', body, re.S)
        sims = []
        for c in re.finditer(r'<a class="sim-card[^"]*" href="([^"]+)"[^>]*>(.*?)</a>', body, re.S):
            href, card = c.group(1), c.group(2)
            svg = re.search(r'<svg[^>]*>(.*?)</svg>', card, re.S)
            icon = svg.group(1).strip() if svg else ''
            for tag in re.findall(r'<\s*([a-zA-Z0-9]+)', icon):
                if tag.lower() not in ALLOWED_SVG:
                    sys.exit('unexpected <%s> in the icon for %s' % (tag, href))
            if re.search(r'\son\w+\s*=|javascript:', icon, re.I):
                sys.exit('script-like attribute in the icon for %s' % href)
            title_html = re.search(r'class="sim-card-title">(.*?)</span>\s*<span class="sim-card-blurb"', card, re.S).group(1)
            badge_m = re.search(r'<sup[^>]*>(.*?)</sup>', title_html, re.S)
            tier_m = re.search(r'class="sim-tier ([^"]+)">(.*?)</span>', card, re.S)
            sims.append({
                'path': href,
                'title': text(re.sub(r'<sup.*?</sup>', '', title_html, flags=re.S)),
                'badge': text(badge_m.group(1)) if badge_m else '',
                'tier': text(tier_m.group(2)) if tier_m else '',
                'blurb': text(re.search(r'class="sim-card-blurb">(.*?)</span>', card, re.S).group(1)),
                'icon': re.sub(r'\s+', ' ', icon),
            })
        sections.append({'key': key, 'title': title, 'note': text(note_m.group(1)) if note_m else '', 'sims': sims})

    total = sum(len(s['sims']) for s in sections)
    if total < 10:
        sys.exit('only %d simulations found; has the catalog markup changed?' % total)

    out = ['<?php',
           '/**',
           " * Parker's Physics simulation catalog.",
           ' *',
           ' * GENERATED by tools/build-parkers-catalog.py from simulations.html',
           " * in the Parker's Physics repository. Do not edit by hand; re-run the",
           ' * script instead. Filter with infinity_parkers_catalog.',
           ' *',
           ' * @package Infinity',
           ' */',
           '',
           "if (!defined('ABSPATH')) {",
           '    exit;',
           '}',
           '',
           'function infinity_parkers_catalog_data() {',
           '    return array(']
    for s in sections:
        out.append('        array(')
        out.append("            'key'   => %s," % php_str(s['key']))
        out.append("            'title' => %s," % php_str(s['title']))
        out.append("            'note'  => %s," % php_str(s['note']))
        out.append("            'sims'  => array(")
        for sim in s['sims']:
            out.append('                array(%s),' % ', '.join(
                '%s => %s' % (php_str(k), php_str(sim[k])) for k in ('path', 'title', 'badge', 'tier', 'blurb', 'icon')))
        out.append('            ),')
        out.append('        ),')
    out += ['    );', '}', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print('%d sections, %d simulations -> %s' % (len(sections), total, os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
