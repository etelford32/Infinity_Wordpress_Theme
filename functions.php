/**
 * Canonical URLs for non-singular views (core only covers singular).
 */
function infinity_canonical_tag() {
    if (defined('WPSEO_VERSION') || class_exists('RankMath') || defined('AIOSEO_VERSION')) {
        return;
    }
    if (is_singular()) {
        return; // core handles it
    }
    $canonical = '';
    if (is_front_page()) {
        $canonical = home_url('/');
    } elseif (is_home()) {
        $canonical = get_permalink(get_option('page_for_posts'));
    } elseif (is_category() || is_tag() || is_tax()) {
        $canonical = get_term_link(get_queried_object());
    } elseif (is_post_type_archive()) {
        $canonical = get_post_type_archive_link(get_query_var('post_type'));
    }
    if ($canonical && !is_wp_error($canonical)) {
        printf('<link rel="canonical" href="%s">' . "\n", esc_url($canonical));
    }
}
add_action('wp_head', 'infinity_canonical_tag', 4);

/**
 * BreadcrumbList structured data on single posts.
 */
function infinity_breadcrumb_json_ld() {
    if (defined('WPSEO_VERSION') || class_exists('RankMath') || defined('AIOSEO_VERSION')) {
        return;
    }
    if (!is_singular('post')) {
        return;
    }
    $items = array(array(
        '@type'    => 'ListItem',
        'position' => 1,
        'name'     => get_bloginfo('name'),
        'item'     => home_url('/'),
    ));
    $cats = get_the_category();
    if ($cats) {
        $items[] = array(
            '@type'    => 'ListItem',
            'position' => 2,
            'name'     => $cats[0]->name,
            'item'     => get_category_link($cats[0]),
        );
    }
    $items[] = array(
        '@type'    => 'ListItem',
        'position' => count($items) + 1,
        'name'     => get_the_title(),
        'item'     => get_permalink(),
    );
    printf(
        '<script type="application/ld+json">%s</script>' . "\n",
        wp_json_encode(array(
            '@context'        => 'https://schema.org',
            '@type'           => 'BreadcrumbList',
            'itemListElement' => $items,
        ), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)
    );
}
add_action('wp_head', 'infinity_breadcrumb_json_ld', 7);

/**
 * Indexing hygiene: keep thin/duplicate views out of the index.
 *
 * GSC showed ~3,850 duplicate URLs. Attachment pages, date/author
 * archives, and search results are the classic sources: noindex the
 * archives, disable attachment pages entirely (redirecting old ones
 * to their file), and let canonicals cover the rest.
 */
function infinity_wp_robots($robots) {
    if (is_date() || is_author() || is_search() || is_attachment()) {
        $robots['noindex'] = true;
        $robots['follow']  = true;
    }
    return $robots;
}
add_filter('wp_robots', 'infinity_wp_robots');

// WP 6.4+: stop generating attachment pages at all
add_filter('wp_attachment_pages_enabled', '__return_false');

// Legacy attachment URLs redirect to the file itself
function infinity_attachment_redirect() {
    if (is_attachment()) {
        $url = wp_get_attachment_url(get_queried_object_id());
        if ($url) {
            wp_safe_redirect($url, 301);
            exit;
        }
    }
}
add_action('template_redirect', 'infinity_attachment_redirect');
