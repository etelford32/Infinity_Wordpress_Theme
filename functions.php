/**
 * Theme Setup
 */
function infinity_theme_setup() {
    // Make theme available for translation
    load_theme_textdomain('infinity', INFINITY_DIR . '/languages');

    // Add default posts and comments RSS feed links to head
    add_theme_support('automatic-feed-links');

    // Let WordPress manage the document title
    add_theme_support('title-tag');

    // Enable support for Post Thumbnails
    add_theme_support('post-thumbnails');

    // Add support for responsive embedded content
    add_theme_support('responsive-embeds');

    // Add support for HTML5 markup
    add_theme_support('html5', array(
        'search-form',
        'comment-form',
        'comment-list',
        'gallery',
        'caption',
        'style',
        'script',
    ));

    // Add support for custom logo
    add_theme_support('custom-logo', array(
        'height'      => 100,
        'width'       => 400,
        'flex-width'  => true,
        'flex-height' => true,
    ));

    // Add support for selective refresh for widgets
    add_theme_support('customize-selective-refresh-widgets');

    // Register navigation menus
    register_nav_menus(array(
        'primary' => esc_html__('Primary Menu', 'infinity'),
        'footer'  => esc_html__('Footer Menu', 'infinity'),
    ));
}
add_action('after_setup_theme', 'infinity_theme_setup');

/**
 * Enqueue Scripts and Styles
 */
function infinity_enqueue_scripts() {
    // Main stylesheet
    wp_enqueue_style('infinity-style', get_stylesheet_uri(), array(), INFINITY_VERSION);

    // Orbitron display face for headings and the wordmark
    wp_enqueue_style(
        'infinity-orbitron',
        'https://fonts.googleapis.com/css2?family=Orbitron:wght@500;700;900&display=swap',
        array(),
        null
    );

    /*
     * The React app (~270 KB JS + 38 KB CSS) only mounts on templates
     * that render #infinity-root: the posts-page fallback (index.php)
     * and the Parker's App Shell page template. Content pages skip it
     * entirely.
     */
    $load_app = (is_home() && !is_front_page()) || is_page_template('template-app.php');
    $load_app = apply_filters('infinity_load_app', $load_app);
    if (!$load_app) {
        // Comment reply script still needed on posts
        if (is_singular() && comments_open() && get_option('thread_comments')) {
            wp_enqueue_script('comment-reply');
        }
        return;
    }

    // React app styles (will be generated by Vite/Next.js)
    if (file_exists(INFINITY_DIR . '/frontend/dist/style.css')) {
        wp_enqueue_style(
            'infinity-app-styles',
            INFINITY_URI . '/frontend/dist/style.css',
            array('infinity-style'),
            INFINITY_VERSION
        );
    }

    // React app scripts (will be generated by Vite/Next.js)
    if (file_exists(INFINITY_DIR . '/frontend/dist/main.js')) {
        wp_enqueue_script(
            'infinity-app',
            INFINITY_URI . '/frontend/dist/main.js',
            array(),
            INFINITY_VERSION,
            true
        );
    }

    // Pass PHP data to JavaScript
    $frontend_data = array(
        'restUrl'        => esc_url_raw(rest_url()),
        'nonce'          => wp_create_nonce('wp_rest'),
        'graphqlUrl'     => esc_url_raw(home_url('/graphql')),
        'siteUrl'        => esc_url_raw(home_url('/')),
        'siteName'       => get_bloginfo('name'),
        'themePath'      => INFINITY_URI,
        'steamUrl'       => esc_url_raw(get_option('infinity_steam_url', 'https://store.steampowered.com/app/4094340/Explore_the_Universe_2175/')),
        'steamLabel'     => get_option('infinity_steam_label', 'Explore the Universe'),
        'currentUserId'  => get_current_user_id(),
        'isUserLoggedIn' => is_user_logged_in(),
        'theme'          => get_option('infinity_theme_mode', 'dark-cosmic'),
        'stripeKey'      => get_option('infinity_stripe_publishable_key', ''),
        'stripe'         => array(
            'enabled'        => infinity_stripe_configured(),
            'publishableKey' => get_option('infinity_stripe_publishable_key', ''),
            'prices'         => array(
                'monthly' => get_option('infinity_stripe_price_monthly', ''),
                'yearly'  => get_option('infinity_stripe_price_yearly', ''),
            ),
            'premiumPrice'   => infinity_get_premium_price(),
        ),
    );

    // Add user subscription data if logged in
    if (is_user_logged_in()) {
        $user_id = get_current_user_id();
        $frontend_data['subscription'] = array(
            'status'            => infinity_get_user_subscription_status($user_id),
            'isPremium'         => infinity_has_active_subscription($user_id),
            'currentPeriodEnd'  => (int) get_user_meta($user_id, 'infinity_subscription_current_period_end', true),
            'cancelAtPeriodEnd' => get_user_meta($user_id, 'infinity_subscription_cancel_at_period_end', true) === '1',
        );
    }

    // Allow filtering of frontend data
    $frontend_data = apply_filters('infinity_frontend_data', $frontend_data);

    wp_localize_script('infinity-app', 'infinityData', $frontend_data);

    // Comment reply script
    if (is_singular() && comments_open() && get_option('thread_comments')) {
        wp_enqueue_script('comment-reply');
    }
}
add_action('wp_enqueue_scripts', 'infinity_enqueue_scripts');

/**
 * Load the Vite-built app bundle as an ES module
 *
 * The build emits ES module output (export statements, dynamic imports),
 * which fails with a SyntaxError when loaded via a classic script tag.
 */
function infinity_module_script_loader_tag($tag, $handle, $src) {
    if ('infinity-app' === $handle) {
        $tag = sprintf(
            '<script type="module" src="%s" id="%s-js"></script>' . "\n",
            esc_url($src),
            esc_attr($handle)
        );
    }
    return $tag;
}
add_filter('script_loader_tag', 'infinity_module_script_loader_tag', 10, 3);

/**
 * Resource hints: preconnect to the Steam CDN on the front page,
 * where the game's key art is loaded from it.
 */
function infinity_resource_hints($urls, $relation_type) {
    if ('preconnect' === $relation_type) {
        $urls[] = array('href' => 'https://fonts.googleapis.com');
        $urls[] = array('href' => 'https://fonts.gstatic.com', 'crossorigin');
        if (is_front_page()) {
            $urls[] = array(
                'href' => 'https://shared.akamai.steamstatic.com',
                'crossorigin',
            );
        }
    }
    return $urls;
}
add_filter('wp_resource_hints', 'infinity_resource_hints', 10, 2);

